#!/usr/bin/env node
/**
 * Generate the per-service database roles and grants.
 * ---------------------------------------------------------------------------
 *
 *     npm run db:roles            -> docs/db-roles.sql
 *     npm run db:roles -- --out /tmp/roles.sql
 *
 * WHAT IT PRODUCES AND WHY
 * Today one role reaches every schema. `search_path` stops a module reading a
 * sibling's table by convention — `npm run test:isolation` is what tests that
 * convention — but a qualified name like `people.employee_profiles` still
 * resolves from the `work` pool, because the role is allowed to read it. With a
 * role per service it does not: Postgres answers `42501 permission denied`.
 *
 * The services come from src/platform/service-map.js, the same definition
 * platform/db.js uses to pick which credential a pool connects with. One
 * source, so the grants and the connections cannot disagree.
 *
 * PURELY ADDITIVE, DELIBERATELY
 * The script emits CREATE ROLE and GRANT and nothing else. No REVOKE, no DROP,
 * no ALTER on an existing role. Revoking from the migration role would break
 * migrations, and a script that can only add is a script that can be run on
 * production without a rollback plan — the rollback is "do not set the
 * DATABASE_URL_* variable", which changes nothing in the database at all.
 *
 * NO PASSWORDS IN HERE
 * Roles are created with LOGIN and no password, so the output is safe to
 * commit and to paste into a ticket. A LOGIN role with no password cannot
 * connect, so the operator sets one per role separately — the generated file
 * says how, and says not to commit it.
 *
 * THIS SCRIPT NEVER TOUCHES A DATABASE. It reads a JavaScript object and
 * writes a text file. Applying the SQL is a person's deliberate act, as every
 * production DDL change in this repo is.
 */

const fs = require('fs')
const path = require('path')

const { SERVICES, SERVICE_NAMES, roleFor } = require('../src/platform/service-map')

const DEFAULT_OUT = path.join(__dirname, '..', 'docs', 'db-roles.sql')

// Every module pool's search_path is `<module>,extensions`, so a role that
// cannot see `extensions` cannot call gen_random_uuid() and every INSERT with a
// uuid default fails. EXECUTE on functions is granted to PUBLIC by default, so
// USAGE on the schema is the whole requirement.
const SHARED_SCHEMAS = ['extensions']

const DML = 'SELECT, INSERT, UPDATE, DELETE'

const header = () => `-- Per-service database roles and grants
-- =========================================================================
-- GENERATED by scripts/gen-db-roles.js from src/platform/service-map.js.
-- Do not hand-edit: change the service map, then run \`npm run db:roles\`.
--
-- WHAT THIS DOES
--   Creates one login role per service and grants it USAGE and DML on ONLY the
--   schemas that service owns. A service touching a schema it does not own then
--   gets \`42501 permission denied\` from Postgres instead of a quietly wrong
--   answer. It makes \`search_path\` isolation enforced rather than conventional.
--
-- WHAT IT DOES NOT DO
--   No REVOKE, no DROP, no ALTER of an existing role, no schema change, no data
--   change. It is additive only, so it needs no rollback plan: nothing in the
--   application connects as these roles until a DATABASE_URL_<SERVICE> variable
--   is set, and unsetting that variable is the rollback.
--
-- RUN IT AS THE ROLE THAT RUNS MIGRATIONS
--   The ALTER DEFAULT PRIVILEGES statements below apply to tables created by
--   the role executing them. Migrations run as the database owner (\`postgres\`
--   on Supabase, which is also who the SQL editor runs as), so run this there.
--   Executed as anyone else, future tables will not inherit the grants and the
--   next migration will quietly produce tables the services cannot read.
--
-- ORDER
--   1. Run this file.
--   2. Set a password per role (see the end of this file). Never commit them.
--   3. Put the connection strings in DATABASE_URL_<SERVICE> for ONE service.
--   4. \`npm run test:db-roles\` — proves each role reaches its own schemas and
--      is refused on every other one.
--   5. Repeat 3-4 for the next service.
--
-- Dev first. Production only after dev passes step 4.
-- =========================================================================

BEGIN;
`

const roleBlock = (service) => {
  const role = roleFor(service)
  const schemas = SERVICES[service]
  const list = schemas.join(', ')

  const lines = []
  lines.push('')
  lines.push(`-- ── ${service}${' '.repeat(Math.max(1, 14 - service.length))}${schemas.length} schema(s): ${list}`)
  lines.push(`-- ${'─'.repeat(70)}`)
  // Idempotent: re-running the file must not fail on a role that already
  // exists, because step 5 above runs it once per service.
  lines.push(`DO $$ BEGIN`)
  lines.push(`  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}') THEN`)
  lines.push(`    CREATE ROLE ${role} LOGIN;`)
  lines.push(`  END IF;`)
  lines.push(`END $$;`)
  lines.push('')

  for (const schema of [...SHARED_SCHEMAS, ...schemas]) {
    lines.push(`GRANT USAGE ON SCHEMA ${schema} TO ${role};`)
  }
  lines.push('')

  for (const schema of schemas) {
    lines.push(`GRANT ${DML} ON ALL TABLES IN SCHEMA ${schema} TO ${role};`)
    lines.push(`GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ${schema} TO ${role};`)
  }
  lines.push('')

  lines.push(`-- Future tables and sequences, so the next migration does not have to remember.`)
  for (const schema of schemas) {
    lines.push(`ALTER DEFAULT PRIVILEGES IN SCHEMA ${schema} GRANT ${DML} ON TABLES TO ${role};`)
    lines.push(`ALTER DEFAULT PRIVILEGES IN SCHEMA ${schema} GRANT USAGE, SELECT ON SEQUENCES TO ${role};`)
  }

  return lines.join('\n')
}

const footer = () => `
COMMIT;

-- =========================================================================
-- VERIFY — read-only, run after the COMMIT above.
-- =========================================================================
-- Every service role, and the schemas it may use. Each role must show ONLY its
-- own schemas plus \`extensions\`.
SELECT r.rolname AS role,
       string_agg(n.nspname, ', ' ORDER BY n.nspname) AS usable_schemas
  FROM pg_roles r
  CROSS JOIN pg_namespace n
 WHERE r.rolname LIKE 'svc\\_%'
   AND n.nspname NOT LIKE 'pg\\_%'
   AND n.nspname <> 'information_schema'
   AND has_schema_privilege(r.rolname, n.nspname, 'USAGE')
 GROUP BY r.rolname
 ORDER BY r.rolname;

-- =========================================================================
-- PASSWORDS — not in this file, and not in git.
-- =========================================================================
-- Generate one per role, 32 bytes of randomness, and set it with:
--
--   ALTER ROLE svc_core PASSWORD '<paste one here>';
--
-- Generate them with:
--
--   node -e "console.log(require('crypto').randomBytes(24).toString('base64url'))"
--
-- Then build each connection string from the one DATABASE_URL already uses,
-- replacing only the user and password, and put it in DATABASE_URL_<SERVICE>.
--
-- These roles have LOGIN and no password until you do this, and a role with no
-- password cannot connect — so nothing is reachable by accident in between.
`

function main() {
  const argv = process.argv.slice(2)
  const i = argv.indexOf('--out')
  const out = i !== -1 ? path.resolve(argv[i + 1]) : DEFAULT_OUT

  const sql = [header(), ...SERVICE_NAMES.map(roleBlock), footer()].join('\n')

  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, sql, 'utf8')

  const schemas = SERVICE_NAMES.reduce((n, s) => n + SERVICES[s].length, 0)
  console.log(`\nWrote ${path.relative(process.cwd(), out)}`)
  console.log(`  ${SERVICE_NAMES.length} roles, ${schemas} schemas:`)
  for (const service of SERVICE_NAMES) {
    console.log(`    ${roleFor(service).padEnd(18)} ${SERVICES[service].join(', ')}`)
  }
  console.log('\n  Nothing was applied. Run it yourself, dev first.\n')
}

if (require.main === module) main()

module.exports = { roleBlock }
