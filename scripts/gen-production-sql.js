/*
 * Generate a hand-run production SQL script from node-pg-migrate migrations.
 * ---------------------------------------------------------------------------
 * migrate-runner.js refuses the production database by design, so production
 * DDL is applied from a reviewed script. This renders the SAME statements the
 * runner would execute, offline (no database connection), plus the ledger
 * rows, wrapped in one transaction behind a guard that checks each module's
 * ledger is exactly where the script expects it.
 *
 *   node scripts/gen-production-sql.js <out.sql> <module>/<migration> ...
 *
 * e.g. node scripts/gen-production-sql.js docs/production-module9-full.sql \
 *        identity/0003_hr_role people/0002_profile_details
 */

const fs = require('fs')
const path = require('path')
const MigrationBuilder = require('node-pg-migrate/dist/migrationBuilder').default

const [, , outFile, ...targets] = process.argv
if (!outFile || targets.length === 0) {
  console.error('usage: node scripts/gen-production-sql.js <out.sql> <module>/<migration> ...')
  process.exit(1)
}

const ROOT = path.join(__dirname, '..', 'migrations')
const noDb = { query: async () => {}, select: async () => [] }

const render = (mod, name) => {
  const pgm = new MigrationBuilder(noDb, undefined, false, console)
  require(path.join(ROOT, mod, `${name}.js`)).up(pgm)
  return pgm.getSqlSteps().join('\n')
}

// For each module: the ledger row that must be the latest before this runs.
const byModule = new Map()
for (const t of targets) {
  const [mod, name] = t.split('/')
  if (!byModule.has(mod)) byModule.set(mod, [])
  byModule.get(mod).push(name)
}
const previousOf = (mod, first) => {
  const files = fs.readdirSync(path.join(ROOT, mod)).filter((f) => f.endsWith('.js')).sort()
  const i = files.indexOf(`${first}.js`)
  return i > 0 ? files[i - 1].replace(/\.js$/, '') : null
}

const guards = [...byModule.entries()].map(([mod, names]) => {
  const prev = previousOf(mod, names[0])
  return `  -- ${mod}: must be at ${prev}, and none of [${names.join(', ')}] applied yet
  SELECT name INTO latest FROM ${mod}.pgmigrations ORDER BY id DESC LIMIT 1;
  IF latest IS DISTINCT FROM '${prev}' THEN
    RAISE EXCEPTION '${mod}.pgmigrations is at %, expected ${prev}. Nothing was changed.', latest;
  END IF;`
}).join('\n')

const body = targets.map((t) => {
  const [mod, name] = t.split('/')
  return `-- ── ${mod}/${name} ${'─'.repeat(Math.max(4, 66 - mod.length - name.length))}
${render(mod, name)}
INSERT INTO ${mod}.pgmigrations (name, run_on) VALUES ('${name}', now());`
}).join('\n\n')

const sql = `-- ============================================================================
-- PRODUCTION: ${targets.join(', ')}
-- ----------------------------------------------------------------------------
-- GENERATED by scripts/gen-production-sql.js from the migration files — do not
-- edit by hand; regenerate. The statements are exactly what npm run migrate
-- executes, followed by the ledger row each migration would have written.
--
-- One transaction: everything applies or nothing does. The guard first checks
-- every module's ledger is exactly at the expected migration, so running this
-- twice, or out of order, stops before changing anything.
-- ============================================================================

BEGIN;

DO $guard$
DECLARE latest text;
BEGIN
${guards}
END
$guard$;

${body}

COMMIT;

-- Verify: the latest ledger row per module.
${[...byModule.keys()].map((m) => `SELECT '${m}' AS module, name FROM ${m}.pgmigrations ORDER BY id DESC LIMIT 1;`).join('\n')}
`

fs.writeFileSync(outFile, sql)
console.log(`wrote ${outFile} (${sql.split('\n').length} lines)`)
